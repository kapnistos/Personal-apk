import 'package:timezone/timezone.dart' as tz;

import '../../core/format.dart';

/// One event from an iCalendar feed, already expanded to a single occurrence.
class IcsEvent {
  IcsEvent({
    required this.uid,
    required this.title,
    required this.start,
    required this.end,
    required this.allDay,
    this.location = '',
    this.notes = '',
  });

  final String uid;
  final String title;
  final DateTime start;
  final DateTime end;
  final bool allDay;
  final String location;
  final String notes;
}

/// Parses an .ics feed (Proton, Google, Outlook share links) and expands
/// repeating events inside [from, to). Times come back in local time.
List<IcsEvent> parseIcs(String text, {required DateTime from, required DateTime to}) {
  final lines = _unfold(text);
  final out = <IcsEvent>[];
  // Instances moved or cancelled by RECURRENCE-ID overrides, per UID.
  final overridden = <String, Set<DateTime>>{};
  final raw = <Map<String, _Prop>>[];
  Map<String, _Prop>? current;
  List<_Prop>? exdates;

  for (final line in lines) {
    if (line == 'BEGIN:VEVENT') {
      current = {};
      exdates = [];
      continue;
    }
    if (line == 'END:VEVENT') {
      if (current != null) {
        if (exdates!.isNotEmpty) current['EXDATE'] = _Prop('EXDATE', exdates.first.params, exdates.map((e) => e.value).join(','));
        raw.add(current);
      }
      current = null;
      continue;
    }
    if (current == null) continue;
    final p = _Prop.parse(line);
    if (p == null) continue;
    if (p.name == 'EXDATE') {
      exdates!.add(p);
    } else {
      current[p.name] = p;
    }
  }

  for (final e in raw) {
    final rid = e['RECURRENCE-ID'];
    final uid = e['UID']?.value ?? '';
    if (rid != null) (overridden[uid] ??= {}).add(_time(rid).$1);
  }

  for (final e in raw) {
    final startProp = e['DTSTART'];
    if (startProp == null) continue;
    if ((e['STATUS']?.value ?? '').toUpperCase() == 'CANCELLED') continue;
    final (start, allDay) = _time(startProp);
    DateTime end;
    if (e['DTEND'] != null) {
      end = _time(e['DTEND']!).$1;
    } else if (e['DURATION'] != null) {
      end = start.add(_duration(e['DURATION']!.value));
    } else {
      end = allDay ? addDays(start, 1) : start;
    }
    final length = end.difference(start);
    final uid = e['UID']?.value ?? '${start.toIso8601String()}-${e['SUMMARY']?.value}';
    final title = _unescape(e['SUMMARY']?.value ?? '(No title)');
    final location = _unescape(e['LOCATION']?.value ?? '');
    final notes = _unescape(e['DESCRIPTION']?.value ?? '');

    IcsEvent make(DateTime s, String suffix) =>
        IcsEvent(uid: '$uid$suffix', title: title, start: s, end: s.add(length), allDay: allDay, location: location, notes: notes);

    final rrule = e['RRULE'];
    if (rrule == null || e['RECURRENCE-ID'] != null) {
      if (end.isAfter(from) && start.isBefore(to)) {
        out.add(make(start, e['RECURRENCE-ID'] != null ? '@${start.toIso8601String()}' : ''));
      }
      continue;
    }

    final skip = <DateTime>{
      ...?overridden[uid],
      if (e['EXDATE'] != null)
        for (final v in e['EXDATE']!.value.split(','))
          _time(_Prop('EXDATE', e['EXDATE']!.params, v)).$1,
    };
    for (final s in expandRule(rrule.value, start, to)) {
      if (skip.contains(s)) continue;
      if (s.add(length).isAfter(from)) out.add(make(s, '@${s.toIso8601String()}'));
    }
  }
  return out;
}

/// Start times generated by an RRULE, up to [until].
Iterable<DateTime> expandRule(String rule, DateTime start, DateTime until) sync* {
  final parts = {
    for (final kv in rule.split(';'))
      if (kv.contains('=')) kv.split('=')[0].toUpperCase(): kv.split('=')[1],
  };
  final freq = parts['FREQ'] ?? 'DAILY';
  final interval = int.tryParse(parts['INTERVAL'] ?? '1') ?? 1;
  final count = int.tryParse(parts['COUNT'] ?? '');
  final ruleUntil = parts['UNTIL'] == null ? null : _parseStamp(parts['UNTIL']!, null).$1;
  final end = ruleUntil != null && ruleUntil.isBefore(until) ? ruleUntil.add(const Duration(seconds: 1)) : until;
  const days = ['MO', 'TU', 'WE', 'TH', 'FR', 'SA', 'SU'];
  final byDay = (parts['BYDAY'] ?? '')
      .split(',')
      .map((d) => days.indexOf(d.replaceAll(RegExp(r'^[+-]?\d+'), '')) + 1)
      .where((d) => d > 0)
      .toList()
    ..sort();

  var produced = 0;
  for (var i = 0; i < 5000; i++) {
    final List<DateTime> batch;
    switch (freq) {
      case 'WEEKLY':
        final weekStart = DateTime(start.year, start.month, start.day - (start.weekday - 1) + 7 * interval * i,
            start.hour, start.minute, start.second);
        batch = (byDay.isEmpty ? [start.weekday] : byDay)
            .map((d) => DateTime(weekStart.year, weekStart.month, weekStart.day + d - 1, start.hour, start.minute, start.second))
            .where((d) => !d.isBefore(start))
            .toList();
      case 'MONTHLY':
        final d = addMonths(start, interval * i);
        batch = d.day == start.day ? [d] : []; // skip months without that day, like RFC 5545
      case 'YEARLY':
        final d = addMonths(start, 12 * interval * i);
        batch = d.day == start.day ? [d] : [];
      default:
        batch = [DateTime(start.year, start.month, start.day + interval * i, start.hour, start.minute, start.second)];
    }
    if (batch.isEmpty) continue;
    for (final d in batch) {
      if (!d.isBefore(end)) return;
      if (count != null && produced >= count) return;
      produced++;
      yield d;
    }
  }
}

List<String> _unfold(String text) {
  final out = <String>[];
  for (final line in text.replaceAll('\r\n', '\n').split('\n')) {
    if ((line.startsWith(' ') || line.startsWith('\t')) && out.isNotEmpty) {
      out[out.length - 1] += line.substring(1);
    } else if (line.isNotEmpty) {
      out.add(line);
    }
  }
  return out;
}

class _Prop {
  _Prop(this.name, this.params, this.value);
  final String name;
  final Map<String, String> params;
  final String value;

  static _Prop? parse(String line) {
    // The value starts at the first colon outside quotes.
    var inQuotes = false;
    var colon = -1;
    for (var i = 0; i < line.length; i++) {
      final c = line[i];
      if (c == '"') inQuotes = !inQuotes;
      if (c == ':' && !inQuotes) {
        colon = i;
        break;
      }
    }
    if (colon < 0) return null;
    final head = line.substring(0, colon).split(';');
    final params = <String, String>{};
    for (final p in head.skip(1)) {
      final eq = p.indexOf('=');
      if (eq > 0) params[p.substring(0, eq).toUpperCase()] = p.substring(eq + 1).replaceAll('"', '');
    }
    return _Prop(head.first.toUpperCase(), params, line.substring(colon + 1));
  }
}

(DateTime, bool) _time(_Prop p) => _parseStamp(p.value, p.params['TZID'], dateOnly: p.params['VALUE'] == 'DATE');

(DateTime, bool) _parseStamp(String v, String? tzid, {bool dateOnly = false}) {
  final s = v.trim();
  if (dateOnly || s.length == 8) {
    return (DateTime(int.parse(s.substring(0, 4)), int.parse(s.substring(4, 6)), int.parse(s.substring(6, 8))), true);
  }
  final y = int.parse(s.substring(0, 4)), mo = int.parse(s.substring(4, 6)), d = int.parse(s.substring(6, 8));
  final h = int.parse(s.substring(9, 11)), mi = int.parse(s.substring(11, 13));
  final sec = s.length >= 15 ? int.parse(s.substring(13, 15)) : 0;
  if (s.endsWith('Z')) return (DateTime.utc(y, mo, d, h, mi, sec).toLocal(), false);
  if (tzid != null) {
    try {
      final loc = tz.getLocation(tzid);
      final t = tz.TZDateTime(loc, y, mo, d, h, mi, sec);
      return (DateTime.fromMillisecondsSinceEpoch(t.millisecondsSinceEpoch), false);
    } catch (_) {
      // Unknown zone (or zones not loaded): treat as local wall time.
    }
  }
  return (DateTime(y, mo, d, h, mi, sec), false);
}

Duration _duration(String v) {
  final m = RegExp(r'P(?:(\d+)W)?(?:(\d+)D)?(?:T(?:(\d+)H)?(?:(\d+)M)?(?:(\d+)S)?)?').firstMatch(v);
  if (m == null) return Duration.zero;
  int g(int i) => int.tryParse(m.group(i) ?? '') ?? 0;
  return Duration(days: g(1) * 7 + g(2), hours: g(3), minutes: g(4), seconds: g(5));
}

String _unescape(String s) =>
    s.replaceAll(r'\n', '\n').replaceAll(r'\N', '\n').replaceAll(r'\,', ',').replaceAll(r'\;', ';').replaceAll(r'\\', '\\');
